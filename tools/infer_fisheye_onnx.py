#!/usr/bin/env python3
"""Run exported ROSA with ONNX Runtime; no OpenMMLab dependency required."""
import argparse
import hashlib
import json
from pathlib import Path
import sys
import time

ROSA = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROSA))
LOCAL_DEPS = ROSA / 'work_dirs/onnx_deps_py38'
if sys.version_info[:2] == (3, 8) and LOCAL_DEPS.is_dir():
    sys.path.insert(0, str(LOCAL_DEPS))

from deployment.runtime import (CAMERAS, CLASSES, COORDINATES, compare_outputs,
    create_session, image_input, load_npz, postprocess)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--model', type=Path, required=True)
    source = parser.add_mutually_exclusive_group(required=True)
    source.add_argument('--input', type=Path, help='Exporter-generated complete input .npz')
    source.add_argument('--images', nargs=4, type=Path, metavar=('FRONT', 'LEFT', 'RIGHT', 'REAR'))
    source.add_argument('--samples', type=Path, help='Exporter-generated JSON manifest; no dataset PKL required')
    parser.add_argument('--calibration', type=Path, help='Converted calibration .npz for --images')
    parser.add_argument('--data-root', type=Path, help='Relocate the dataset used by --samples, e.g. on the server')
    parser.add_argument('--provider', choices=('cuda', 'cpu'), default='cuda')
    parser.add_argument('--threads', type=int, default=2)
    thresholds = parser.add_mutually_exclusive_group()
    thresholds.add_argument('--score-threshold', type=float, default=.1)
    thresholds.add_argument('--threshold-profile', type=Path,
                            help='Checkpoint-bound JSON profile generated by tune_fisheye_thresholds.py')
    parser.add_argument('--nms-iou', type=float, default=.5)
    parser.add_argument('--max-distance', type=float, help='Optional XY radius; disabled by default')
    parser.add_argument('--box-origin', choices=('gravity_center', 'bottom_center'), default='gravity_center')
    parser.add_argument('--start-frame', type=int, default=0)
    parser.add_argument('--max-frames', type=int)
    parser.add_argument('--reference', type=Path, help='Compare one input to the exporter PyTorch .npz reference')
    parser.add_argument('--profile', action='store_true')
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    if args.images and args.calibration is None:
        parser.error('--images requires --calibration from the export bundle')
    if args.reference and not args.input:
        parser.error('--reference requires a single --input')
    if args.start_frame < 0 or (args.max_frames is not None and args.max_frames < 1):
        parser.error('Invalid frame interval')
    manifest_path = args.model.with_suffix('.json')
    manifest = json.loads(manifest_path.read_text())
    if manifest['coordinates'] != COORDINATES:
        raise ValueError('Unrecognized model coordinate contract')
    digest = hashlib.sha256()
    with args.model.open('rb') as stream:
        for block in iter(lambda: stream.read(4*1024*1024), b''):
            digest.update(block)
    if digest.hexdigest() != manifest['onnx_sha256']:
        raise ValueError('ONNX model does not match its metadata/checkpoint manifest')
    if args.nms_iou != manifest['postprocessing']['nms_iou']:
        parser.error('NMS IoU differs from the verified checkpoint contract')
    class_thresholds = None
    if args.threshold_profile:
        profile = json.loads(args.threshold_profile.read_text())
        if profile.get('format_version') != 1 or profile.get('checkpoint_sha256') != manifest['checkpoint_sha256']:
            parser.error('Threshold profile belongs to a different checkpoint or has an unknown format')
        if profile.get('nms_iou') != args.nms_iou:
            parser.error('Threshold profile NMS differs from the model contract')
        class_thresholds = profile['score_thresholds']
    if args.samples:
        document = json.loads(args.samples.read_text())
        samples = document['samples']
        root = args.data_root or Path(document.get('data_root', '.'))
        for sample in samples:
            if 'image_relative_paths' in sample:
                sample['image_paths'] = [str(root / path) for path in sample['image_relative_paths']]
            elif args.data_root:
                parser.error('Old sample manifest cannot be relocated; regenerate it with --prepare-only')
    elif args.images:
        samples = [dict(token='external_images', image_paths=[str(p) for p in args.images],
                        calibration=str(args.calibration.resolve()))]
    else:
        samples = [dict(token=args.input.stem, input=str(args.input.resolve()))]
    stop = None if args.max_frames is None else args.start_frame + args.max_frames
    samples = samples[args.start_frame:stop]
    if not samples:
        parser.error('No selected samples')
    session = create_session(args.model, args.provider, args.threads, args.profile)
    expected = {item.name: item for item in session.get_inputs()}
    frames, timings, comparison = [], [], None
    for index, sample in enumerate(samples):
        if 'input' in sample:
            feed = load_npz(sample['input'])
        else:
            calibration = Path(sample['calibration'])
            if not calibration.is_absolute():
                calibration = args.samples.parent / calibration
            feed = load_npz(calibration)
            feed['images'] = image_input(sample['image_paths'])
        if set(feed) != set(expected):
            raise ValueError(f'Input fields differ: {set(feed)} vs {set(expected)}')
        for key, value in feed.items():
            if list(value.shape) != expected[key].shape:
                raise ValueError(f'{key}: shape {value.shape} differs from {expected[key].shape}')
        started = time.perf_counter()
        raw = session.run(None, feed)
        timings.append(time.perf_counter() - started)
        if args.reference:
            comparison = compare_outputs(raw, load_npz(args.reference))
            print('PyTorch parity:', json.dumps(comparison), flush=True)
        prediction = postprocess(*raw, score_threshold=args.score_threshold,
            nms_iou=args.nms_iou, max_distance=args.max_distance, origin=args.box_origin,
            class_score_thresholds=class_thresholds)
        frames.append(dict(index=args.start_frame+index, token=str(sample['token']), **prediction))
        print(f'{index+1}/{len(samples)} | boxes={len(prediction["scores"])} | '
              f'network={timings[-1]:.3f}s | {sample["token"]}', flush=True)
    payload = dict(format_version=2, box_origin=args.box_origin, coordinates=COORDINATES,
        model=str(args.model.resolve()), checkpoint_sha256=manifest['checkpoint_sha256'],
        classes=CLASSES, camera_order=CAMERAS,
        score_threshold=None if class_thresholds is not None else args.score_threshold,
        class_score_thresholds=class_thresholds,
        nms_iou=args.nms_iou, max_distance=args.max_distance, frames=frames,
        providers=session.get_providers(), seconds_per_frame=timings, pytorch_parity=comparison)
    if args.profile:
        payload['onnxruntime_profile'] = session.end_profiling()
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(payload, indent=2, allow_nan=False) + '\n')
    if comparison and not comparison['passed']:
        raise RuntimeError('ONNX/PyTorch parity failed; output is diagnostic, not verified deployment output')


if __name__ == '__main__':
    main()
